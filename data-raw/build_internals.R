createSDR <- function(n, permarr=PermArr){
  
  createPaleyMod3 <- function(q=19){
    quad_char <- function(a, q=19){
      # assume q is prime
      if(a < 0){
        while(a < 0){
          a <- a + q
        }
      }
      ans <- -1
      if(a %% q == 0){
        ans <- 0
      }
      x <- seq(0, q-1, 1)
      x <- x**2 %% q
      if(any(a==x) && a %% q != 0){
        ans <- 1
      }
      return(ans)
    }
    Q <- matrix(NA, nrow=q, ncol=q)
    for(i in 1:NROW(Q)){
      for(j in 1:NCOL(Q)){
        Q[i,j] <- quad_char(i-j, q) 
      }
    }
    
    H <- diag(q+1) + rbind(c(0, rep(1, q)),
                           cbind(rep(-1, q), Q))
    H
  }
  H1 <- createPaleyMod3()
  h <- matrix(c(1,1,1,-1), nrow=2)
  H <- H1 %x% h %x% h
  # create indices from PermArr
  indicies <- do.call(rbind, apply(PermArr, 2, FUN=function(x){ cbind(x, x[c(2:length(x), 1)]) }, simplify=FALSE))
  if(NROW(indicies) >= n){
    indicies <- indicies[1:n,]
  }else{
    while(NROW(indicies) < n){
      indicies <- rbind(indicies, indicies)
    }
    indicies <- indicies[1:n,]
  }
  
  SDRfactors <- 1 + 2^(-3/2)*(H[indicies[,1],] - H[indicies[,2],])
  SDRfactors
}


